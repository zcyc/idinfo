import (
	"bytes"
	"compress/gzip"
	"encoding/base64"
	"io"
	"strconv"
	"strings"
)

type isbnRange struct {
	kind               byte
	prefix, group      int
	start, end, length int
	name               string
}

var isbnRanges = loadISBNRanges()

func loadISBNRanges() []isbnRange {
	compressed, err := base64.StdEncoding.DecodeString(strings.Join(strings.Fields(isbnRangeData), ""))
	if err != nil {
		panic(err)
	}
	reader, err := gzip.NewReader(bytes.NewReader(compressed))
	if err != nil {
		panic(err)
	}
	data, err := io.ReadAll(reader)
	if err != nil {
		panic(err)
	}
	if err := reader.Close(); err != nil {
		panic(err)
	}

	lines := strings.Split(strings.TrimSpace(string(data)), "\n")
	ranges := make([]isbnRange, 0, len(lines))
	for _, line := range lines {
		fields := strings.SplitN(strings.TrimSuffix(line, "\r"), "\t", 7)
		if len(fields) != 7 || len(fields[0]) != 1 {
			panic("invalid embedded ISBN range")
		}
		values := make([]int, 5)
		for index := range values {
			value, err := strconv.Atoi(fields[index+1])
			if err != nil {
				panic(err)
			}
			values[index] = value
		}
		ranges = append(ranges, isbnRange{
			kind: fields[0][0], prefix: values[0], group: values[1],
			start: values[2], end: values[3], length: values[4], name: fields[6],
		})
	}
	return ranges
}

func isbnRangeLength(kind byte, prefix, group, segment int) (int, bool) {
	for _, rule := range isbnRanges {
		if rule.kind == kind && rule.prefix == prefix && rule.group == group && rule.start <= segment && segment <= rule.end {
			return rule.length, true
		}
	}
	return 0, false
}

